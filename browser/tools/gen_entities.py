#!/usr/bin/env python3
"""Generate crates/html/src/entities_table.rs from crates/html/data/entities.json.

entities.json is the WHATWG named character reference table (CC BY 4.0,
Copyright WHATWG). Run from the browser/ directory. A test in the html crate
checks the generated table against the JSON, so a stale table fails CI.
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
data = json.load(open(os.path.join(root, "crates/html/data/entities.json"), encoding="utf-8"))
rows = []
for name, v in data.items():
    assert name.startswith("&")
    cps = v["codepoints"]
    assert 1 <= len(cps) <= 2
    rows.append((name[1:].encode("ascii"), cps[0], cps[1] if len(cps) == 2 else 0))
rows.sort()
out = []
out.append("// @generated by tools/gen_entities.py from data/entities.json. Do not edit.\n")
out.append("// Source: WHATWG HTML named character references, CC BY 4.0, Copyright WHATWG.\n\n")
out.append("/// Longest name in the table, in bytes (without the leading `&`).\n")
out.append("pub const LONGEST_NAME: usize = %d;\n\n" % max(len(r[0]) for r in rows))
out.append("/// Every named character reference, sorted by name bytes, without the leading\n")
out.append("/// `&`. Each entry is (name, first code point, second code point or 0).\n")
out.append("pub static ENTITIES: [(&[u8], u32, u32); %d] = [\n" % len(rows))
for n, a, b in rows:
    out.append('    (b"%s", 0x%X, 0x%X),\n' % (n.decode(), a, b))
out.append("];\n")
open(os.path.join(root, "crates/html/src/entities_table.rs"), "w").write("".join(out))
print(len(rows), "entities")
